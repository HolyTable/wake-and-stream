// wake-and-stream – the widget (Notification Center and desktop), sizes small and medium.
// Shows the PC state and the buttons that make sense right now – the same choices as the menu bar.
// Buttons are App Intents: a click runs WidgetActionIntent right here (Notification Center stays open),
// which hands the request to the widget app (file widget-request + a system notification).
// Only "open VPN" / "start app" are links, because they open an app anyway.
import AppIntents
import SwiftUI
import WidgetKit

/// The one intent behind all widget buttons. Its description (Metadata.appintents) is generated by build.sh,
/// because the tool that normally does this only comes with Xcode.
struct WidgetActionIntent: AppIntent {
    static var title: LocalizedStringResource = "Wake and Stream"
    @Parameter(title: "Action") var action: String

    init() {}
    init(action: String) { self.action = action }

    func perform() async throws -> some IntentResult {
        WidgetRequest.send(action)
        // give the app a moment to update the state, so the widget redraws with the new state
        try? await Task.sleep(nanoseconds: 600_000_000)
        return .result()
    }
}

struct Entry: TimelineEntry {
    let date: Date
    let state: PCState?     // nil = the widget app is not running
}

struct Provider: TimelineProvider {
    func placeholder(in context: Context) -> Entry { Entry(date: Date(), state: Self.sample) }

    func getSnapshot(in context: Context, completion: @escaping (Entry) -> Void) {
        let now = Date()
        completion(Entry(date: now, state: Self.current(now) ?? (context.isPreview ? Self.sample : nil)))
    }

    func getTimeline(in context: Context, completion: @escaping (Timeline<Entry>) -> Void) {
        let now = Date()
        // the app redraws the widget on every change; this is only the fallback
        completion(Timeline(entries: [Entry(date: now, state: Self.current(now))],
                            policy: .after(now.addingTimeInterval(5 * 60))))
    }

    /// State from the app – only if it is fresh (the app writes it every 10 s).
    static func current(_ now: Date) -> PCState? {
        guard let s = PCState.load(), now.timeIntervalSince(s.time) < 120 else { return nil }
        return s
    }

    /// Shown in the widget gallery
    static var sample: PCState {
        var s = PCState()
        s.home = true; s.lang = Texts.systemLang
        return s
    }
}

// MARK: - what to show

struct Action: Identifiable {
    let id: String          // action name in the link
    let title: String
    let symbol: String
    var destructive = false
    var tint: Color? = nil  // own color for the highlighted button (e.g. orange for "end …")
    var url: URL { URL(string: "\(WAS.scheme)://\(id)")! }
}

struct Status {
    let title: String
    let text: String
    let detail: String?
    let symbol: String
    let color: Color
    var main: [Action] = []     // full-width buttons
    var power: [Action] = []    // small round buttons in the corner (shut down / sleep, or cancel)
    var confirming = false      // showing "really …?"
}

extension PCState {
    var status: Status {
        let title = t("title")
        if !home {
            return Status(title: title, text: t("s_nohome"), detail: nil, symbol: "wifi.exclamationmark", color: .orange,
                          main: [Action(id: "vpn", title: t("a_vpn"), symbol: "lock.shield")])
        }
        if !busy.isEmpty {
            // what is running right now – its own text and symbol per action
            let (key, detail, symbol, color): (String, String?, String, Color) = {
                switch busy {
                case "work" where on: return ("busy_work", nil, "briefcase", .green)
                case "play" where on: return ("busy_play", nil, "gamecontroller", .green)
                case "work":          return ("busy_on", t("busy_then_work"), "power", .green)
                case "play":          return ("busy_on", t("busy_then_play"), "power", .green)
                case "on":            return ("busy_on", nil, "power", .green)
                case "stop":          return ("busy_stop", nil, "stop.fill", .orange)
                case "release":       return ("busy_release", nil, "stop.fill", .orange)
                case "off":           return ("busy_off", nil, "power", .red)
                case "sleep":         return ("busy_sleep", nil, "moon.zzz", .indigo)
                default:              return ("busy_on", nil, "hourglass", .blue)
                }
            }()
            return Status(title: title, text: t(key), detail: detail, symbol: symbol, color: color)
        }
        if !confirm.isEmpty {
            // second step: "really …?" right in the widget – confirm or cancel (cancels itself after 20 s)
            let a = confirm
            let wake = last == "sleep"
            let (question, button, symbol, color): (String, String, String, Color) = {
                switch a {
                case "off":   return (t("q_off"), t("a_off"), "power", .red)
                case "sleep": return (t("q_sleep"), t("a_sleep"), "moon.zzz", .indigo)
                case "work":  return (t("q_work"), t("a_yes_work"), "briefcase", .green)
                case "play":  return (t("q_play"), t("a_yes_play"), "gamecontroller", .green)
                default:      return (t(wake ? "q_wake" : "q_on"), t(wake ? "a_wake" : "a_on"),
                                      wake ? "sun.max" : "power", .green)
                }
            }()
            return Status(title: title, text: question, detail: a == "off" ? t("q_off_detail") : nil,
                          symbol: "questionmark", color: color,
                          main: [Action(id: "do/" + a, title: button, symbol: symbol, destructive: a == "off"),
                                 Action(id: "cancel", title: t("a_cancel"), symbol: "xmark")],
                          power: [Action(id: "cancel", title: t("a_cancel"), symbol: "xmark")],
                          confirming: true)
        }
        if on {
            var detail: String?
            if rdp { detail = t("s_rdp") }
            if stream == 2 { detail = t("s_stream") } else if stream == 1 { detail = t("s_paused") }
            // while working or playing only "end …" makes sense (orange = end, red = shut down)
            let endWork = Action(id: "do/release", title: t("a_work_end"), symbol: "stop.fill", tint: .orange)
            let endPlay = Action(id: "do/stop", title: t("a_play_end"), symbol: "stop.fill", tint: .orange)
            var main: [Action]
            if rdp {
                main = [endWork]
            } else {
                switch stream {
                case 2: main = [endPlay]
                case 1: main = [Action(id: "do/play", title: t("a_resume"), symbol: "play.fill"), endPlay]
                default: main = [Action(id: "do/work", title: t("a_work"), symbol: "briefcase"),
                                 Action(id: "do/play", title: t("a_play"), symbol: "gamecontroller")]
                }
            }
            return Status(title: title, text: t("s_on"), detail: detail, symbol: "power", color: .green, main: main,
                          power: [Action(id: "ask/off", title: t("a_off"), symbol: "power", destructive: true),
                                  Action(id: "ask/sleep", title: t("a_sleep"), symbol: "moon.zzz")])
        }
        let asleep = last == "sleep"
        return Status(title: title, text: t(asleep ? "s_sleep" : "s_off"), detail: nil,
                      symbol: asleep ? "moon.zzz.fill" : "power", color: asleep ? .indigo : .gray,
                      main: [Action(id: "ask/on", title: t(asleep ? "a_wake" : "a_on"), symbol: asleep ? "sun.max" : "power"),
                             Action(id: "ask/work", title: t("a_work"), symbol: "briefcase"),
                             Action(id: "ask/play", title: t("a_play"), symbol: "gamecontroller")])
    }
}

// MARK: - views

/// Glass-like capsule: translucent fill + light edge. (The real Liquid Glass effect "glassEffect" is not drawn
/// inside widgets – the buttons became invisible – but the widget background itself is glass on macOS 26.)
struct GlassBackground: ViewModifier {
    var tint: Color? = nil
    func body(content: Content) -> some View {
        content
            .background((tint ?? .primary).opacity(tint == nil ? 0.10 : 0.28), in: Capsule())
            .overlay(
                Capsule().strokeBorder(
                    LinearGradient(colors: [.white.opacity(0.45), .white.opacity(0.05)],
                                   startPoint: .top, endPoint: .bottom),
                    lineWidth: 0.8)
            )
    }
}

struct ActionButton: View {
    let action: Action
    var iconOnly = false
    var prominent = false
    var tint: Color = .accentColor

    var body: some View {
        if WAS.preview {
            label
        } else if action.id == "vpn" || action.id == "refresh" {
            Link(destination: action.url) { label }.help(action.title)   // opens an app anyway
        } else {
            Button(intent: WidgetActionIntent(action: action.id)) { label }
                .buttonStyle(.plain)
                .help(action.title)
        }
    }

    var label: some View {
            HStack(spacing: 6) {
                Image(systemName: action.symbol)
                    .font(.system(size: 12, weight: .semibold))
                    .frame(width: 16)
                if !iconOnly {
                    Text(action.title)
                        .font(.system(size: 12, weight: .semibold))
                        .lineLimit(1)
                        .minimumScaleFactor(0.65)
                    Spacer(minLength: 0)
                }
            }
            .foregroundStyle(action.destructive ? Color.red : Color.primary)
            .padding(.horizontal, iconOnly ? 0 : 9)
            .frame(maxWidth: .infinity, minHeight: 28, maxHeight: 28)
            .modifier(GlassBackground(tint: prominent ? tint : nil))
            .contentShape(Capsule())
    }
}

/// Round status badge + name + state
struct StatusBlock: View {
    let status: Status
    var large = false
    var showPower = true
    var compact = false     // small widget with two buttons: name + state in one line, no detail

    var body: some View {
        VStack(alignment: .leading, spacing: large ? 6 : 4) {
            HStack(alignment: .top, spacing: 6) {
                ZStack {
                    Circle().fill(status.color.opacity(0.22))
                    Image(systemName: status.symbol)
                        .font(.system(size: large ? 17 : 14, weight: .bold))
                        .foregroundStyle(status.color)
                        .widgetAccentable()
                }
                .frame(width: large ? 36 : 30, height: large ? 36 : 30)
                Spacer(minLength: 0)
                // shut down / sleep as round icon buttons (rarely used, so small and out of the way)
                if showPower {
                    ForEach(status.power) { ActionButton(action: $0, iconOnly: true).frame(width: 28) }
                }
            }
            Spacer(minLength: 0)
            if compact {
                HStack(alignment: .firstTextBaseline, spacing: 6) {
                    Text(status.title)
                        .font(.system(size: 12, weight: .medium))
                        .foregroundStyle(.secondary)
                    Text(status.text)
                        .font(.system(size: 17, weight: .semibold))
                        .lineLimit(1)
                        .minimumScaleFactor(0.7)
                }
            } else {
                Text(status.title)
                    .font(.system(size: 12, weight: .medium))
                    .foregroundStyle(.secondary)
                Text(status.text)
                    .font(.system(size: large ? 20 : 17, weight: .semibold))
                    .lineLimit(2)
                    .minimumScaleFactor(0.7)
            }
            if let d = status.detail, large || (!status.confirming && !compact) {   // small + "really …?": no room for it
                Text(d).font(.system(size: 11)).foregroundStyle(.secondary).lineLimit(2)
            }
        }
        .frame(maxWidth: .infinity, maxHeight: .infinity, alignment: .topLeading)
    }
}

struct WidgetView: View {
    let entry: Entry
    let family: WidgetFamily

    var status: Status {
        if let state = entry.state { return state.status }
        let lang = Texts.systemLang
        return Status(title: "PC", text: Texts.get("s_noapp", lang), detail: nil, symbol: "exclamationmark",
                      color: .orange,
                      main: [Action(id: "refresh", title: Texts.get("a_start_app", lang), symbol: "play.circle")])
    }

    var body: some View {
        let s = status
        if family == .systemSmall {
            // status at the top, the two most important buttons below
            // (when confirming: one button, "cancel" is the round button in the corner)
            let count = s.confirming ? 1 : 2
            VStack(alignment: .leading, spacing: 6) {
                StatusBlock(status: s, compact: s.main.count > 1 && !s.confirming)
                    .padding(.bottom, 2)
                ForEach(Array(s.main.prefix(count).enumerated()), id: \.offset) { i, a in
                    ActionButton(action: a, prominent: i == 0 || a.tint != nil, tint: a.tint ?? s.color)
                }
            }
        } else {
            // status on the left; on the right: shut down / sleep in the corner, the main buttons below
            HStack(spacing: 14) {
                StatusBlock(status: s, large: true, showPower: false)
                VStack(spacing: 6) {
                    HStack(spacing: 6) {
                        Spacer(minLength: 0)
                        if !s.confirming {
                            ForEach(s.power) { ActionButton(action: $0, iconOnly: true).frame(width: 28) }
                        }
                    }
                    .frame(height: 28)
                    Spacer(minLength: 0)
                    ForEach(Array(s.main.prefix(3).enumerated()), id: \.offset) { i, a in
                        ActionButton(action: a, prominent: i == 0 || a.tint != nil, tint: a.tint ?? s.color)
                    }
                }
                .frame(width: 160)
            }
        }
    }
}

/// Reads the size from the environment (only available inside a real widget)
struct WidgetEntryView: View {
    @Environment(\.widgetFamily) var family
    let entry: Entry
    var body: some View { WidgetView(entry: entry, family: family) }
}

struct WakeAndStreamWidget: Widget {
    var body: some WidgetConfiguration {
        StaticConfiguration(kind: WAS.widgetKind, provider: Provider()) { entry in
            WidgetEntryView(entry: entry)
                .containerBackground(.fill.tertiary, for: .widget)
        }
        .configurationDisplayName("Wake and Stream")
        .description(Texts.get("desc", Texts.systemLang))
        .supportedFamilies([.systemSmall, .systemMedium])
    }
}
